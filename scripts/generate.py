"""Generate the resource classes of the SDK from the OpenAPI snapshot.

Writes, all derived from ``openapi/api.openapi.json``:

* ``src/main/java/com/billionsend/resources/*Resource.java``: one class per
  resource group, one method per operation (with overloads that leave out the
  optional query, body and options), a ``listAll`` / ``searchAll`` iterator
  beside every cursor-paginated list, and the event streams;
* ``src/main/java/com/billionsend/BillionSendApi.java``: the top-level
  resource accessors the client inherits.

Each operation's method is named by its ``operationId``: the dotted path of
the method, segments in camelCase (``emails.receiving.attachments.list`` is
``client.emails().receiving().attachments().list(...)``). An operation whose
``operationId`` is also the group of others is that group's ``get``:
``emails.metrics`` is ``client.emails().metrics().get(...)``, beside
``emails.metrics.links`` and the rest.

Usage::

    python3 scripts/generate.py          # rewrite the generated sources
    python3 scripts/generate.py --check  # fail if they differ from the snapshot
"""

from __future__ import annotations

import argparse
import itertools
import json
import re
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi" / "api.openapi.json"
JAVA = ROOT / "src" / "main" / "java" / "com" / "billionsend"
RESOURCES = JAVA / "resources"
API_OUT = JAVA / "BillionSendApi.java"

HEADER = "// Generated by scripts/generate.py from openapi/api.openapi.json. Do not edit.\n"
HTTP_METHODS = ("get", "put", "post", "patch", "delete")
IDEMPOTENCY_KEY_HEADER = "idempotency-key"
BATCH_VALIDATION_HEADER = "x-batch-validation"
JAVA_KEYWORDS = set(
    """abstract assert boolean break byte case catch char class const continue default do double
    else enum extends final finally float for goto if implements import instanceof int interface
    long native new package private protected public return short static strictfp super switch
    synchronized this throw throws transient try void volatile while var record yield sealed
    permits true false null""".split()
)
WIDTH = 100


def pascal(text: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(text: str) -> str:
    name = pascal(text)
    name = name[:1].lower() + name[1:]
    return name + "Value" if name in JAVA_KEYWORDS else name


# ---------------------------------------------------------------------- javadoc


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("@", "&#64;").replace("*/", "*&#47;")
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", text)


def javadoc(paragraphs: list[str], tags: list[str], indent: str) -> list[str]:
    width = WIDTH - len(indent) - 3
    lines: list[str] = []
    for i, paragraph in enumerate(p for p in paragraphs if p.strip()):
        if i > 0:
            lines.append("")
        text = paragraph.strip() if i == 0 else "<p>" + paragraph.strip()
        lines += textwrap.wrap(text, width, break_long_words=False, break_on_hyphens=False)
    if tags:
        if lines:
            lines.append("")
        for tag in tags:
            wrapped = textwrap.wrap(tag, width, break_long_words=False, break_on_hyphens=False)
            lines.append(wrapped[0])
            lines += ["    " + w for w in wrapped[1:]]
    out = [f"{indent}/**"]
    out += [f"{indent} * {line}" if line else f"{indent} *" for line in lines]
    out.append(f"{indent} */")
    return out


# --------------------------------------------------------------------- operations


@dataclass
class QueryParam:
    name: str
    required: bool
    array: bool
    description: str


@dataclass
class Operation:
    method: str
    path: str
    op_id: str
    group: tuple[str, ...]
    name: str
    summary: str
    description: str
    path_params: list[tuple[str, str]] = field(default_factory=list)  # (wire, java)
    query: list[QueryParam] = field(default_factory=list)
    body: str | None = None  # None, "required" or "optional"
    body_schema: str = ""
    responses: list[str] = field(default_factory=list)
    idempotent: bool = False
    batch_validation: bool = False
    auth: bool = True
    stream: bool = False
    paginated: bool = False


def resolve(spec: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any]:
    while "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].rsplit("/", 1)[1]]
    return schema


def has_id(spec: dict[str, Any], schema: dict[str, Any]) -> bool:
    """Whether every shape an item can take has an ``id`` (the cursor of the next page)."""
    schema = resolve(spec, schema)
    branches = schema.get("anyOf") or schema.get("oneOf")
    if branches:
        return all(has_id(spec, b) for b in branches)
    return "id" in schema.get("properties", {})


def schema_name(schema: dict[str, Any]) -> str:
    return schema["$ref"].rsplit("/", 1)[1] if "$ref" in schema else ""


def build_operations(spec: dict[str, Any]) -> list[Operation]:
    ops: list[Operation] = []
    seen: set[str] = set()
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in HTTP_METHODS:
                continue
            op_id = op.get("operationId")
            if not op_id or op_id in seen:
                raise SystemExit(f"{method.upper()} {path}: every operation needs its own operationId")
            seen.add(op_id)
            *group, name = op_id.split(".")
            o = Operation(
                method=method.upper(),
                path=path,
                op_id=op_id,
                group=tuple(group),
                name=name,
                summary=op.get("summary", ""),
                description=op.get("description", ""),
                auth=op.get("security") != [],
            )
            for p in op.get("parameters", []):
                where, wire = p["in"], p["name"]
                schema = p.get("schema", {})
                if where == "path":
                    o.path_params.append((wire, camel(wire)))
                elif where == "query":
                    types = schema.get("type")
                    types = types if isinstance(types, list) else [types]
                    o.query.append(
                        QueryParam(wire, bool(p.get("required")), "array" in types, p.get("description", ""))
                    )
                elif where == "header" and wire.lower() == IDEMPOTENCY_KEY_HEADER:
                    o.idempotent = True
                elif where == "header" and wire.lower() == BATCH_VALIDATION_HEADER:
                    o.batch_validation = True
                else:
                    raise SystemExit(f"{method.upper()} {path}: unsupported {where} parameter {wire}")
            order = re.findall(r"{([^}]+)}", path)
            o.path_params.sort(key=lambda prm: order.index(prm[0]))
            if [prm[0] for prm in o.path_params] != order:
                raise SystemExit(f"{method.upper()} {path}: path parameters do not match the template")

            body = op.get("requestBody")
            if body:
                content = body.get("content", {})
                if list(content) != ["application/json"]:
                    raise SystemExit(f"{method.upper()} {path}: only JSON request bodies are supported")
                o.body = "optional" if body.get("required") is False else "required"
                o.body_schema = schema_name(content["application/json"].get("schema", {}))

            success = sorted((c, r) for c, r in op["responses"].items() if c.startswith("2"))
            if any("text/event-stream" in r.get("content", {}) for _, r in success):
                o.stream = True
                if o.method != "GET" or o.body:
                    raise SystemExit(f"{method.upper()} {path}: an event stream must be a GET without a body")
            for _, r in success:
                schema = r.get("content", {}).get("application/json", {}).get("schema")
                if schema is not None and schema_name(schema) and schema_name(schema) not in o.responses:
                    o.responses.append(schema_name(schema))

            names = {q.name for q in o.query}
            if {"after", "before"} <= names and not o.stream and len(success) == 1:
                page = resolve(spec, success[0][1]["content"]["application/json"]["schema"])
                props = page.get("properties", {})
                items = props.get("data", {}).get("items", {})
                o.paginated = "has_more" in props and bool(items) and has_id(spec, items)
            if o.body == "optional" and o.query and not any(q.required for q in o.query):
                # Map is an Object: an optional body beside an optional query would make overloads ambiguous.
                raise SystemExit(f"{method.upper()} {path}: an optional body and an optional query")
            ops.append(o)
    return ops


# ----------------------------------------------------------------------- rendering


@dataclass
class Piece:
    kind: str  # path | body | query | options
    java_type: str
    name: str
    optional: bool


def pieces_of(op: Operation, *, options_type: str = "RequestOptions", body: bool = True) -> list[Piece]:
    pieces = [Piece("path", "String", java, False) for _, java in op.path_params]
    if op.body and body:
        pieces.append(Piece("body", "Object", "body", op.body == "optional"))
    if op.query:
        pieces.append(Piece("query", "Map<String, ?>", "query", not any(q.required for q in op.query)))
    pieces.append(Piece("options", options_type, "options", True))
    return pieces


def variants(pieces: list[Piece]) -> list[list[Piece]]:
    optional = [p for p in pieces if p.optional]
    out: list[list[Piece]] = []
    for keep in itertools.product([True, False], repeat=len(optional)):
        kept = {id(p) for p, k in zip(optional, keep, strict=True) if k}
        out.append([p for p in pieces if not p.optional or id(p) in kept])
    return out


def erased(java_type: str) -> str:
    return java_type.split("<", 1)[0]


def signature(pieces: list[Piece]) -> str:
    return ", ".join(f"{p.java_type} {p.name}" for p in pieces)


def link(name: str, pieces: list[Piece]) -> str:
    return "{@link #" + name + "(" + ", ".join(erased(p.java_type) for p in pieces) + ")}"


def delegate_args(full: list[Piece], kept: list[Piece]) -> str:
    names = {p.name for p in kept}
    return ", ".join(
        p.name if p.name in names else f"({p.java_type}) null" for p in full
    )


def query_doc(op: Operation) -> str:
    parts = []
    for q in op.query:
        notes = []
        if q.required:
            notes.append("required")
        if q.array:
            notes.append("a list")
        parts.append("{@code " + q.name + "}" + (f" ({', '.join(notes)})" if notes else ""))
    return "the query parameters, {@code null} values left out: " + ", ".join(parts)


def param_tags(op: Operation, pieces: list[Piece], options_doc: str) -> list[str]:
    tags = []
    for p in pieces:
        if p.kind == "path":
            wire = next(w for w, j in op.path_params if j == p.name)
            tags.append(f"@param {p.name} the {{@code {wire}}} path parameter")
        elif p.kind == "body":
            schema = f" ({{@code {op.body_schema}}})" if op.body_schema else ""
            tags.append(
                f"@param body the request body{schema}: a {{@code Map}}, a {{@code JsonNode}} or any"
                " object the JSON mapper can write" + (", or {@code null} for none" if p.optional else "")
            )
        elif p.kind == "query":
            tags.append(f"@param query {query_doc(op)}")
        else:
            tags.append(f"@param options {options_doc}")
    return tags


def method_doc(op: Operation) -> list[str]:
    paragraphs = [escape(op.summary.rstrip(".") + ".") if op.summary else ""]
    paragraphs += [escape(p) for p in op.description.split("\n\n")]
    if op.idempotent:
        paragraphs.append(
            "Sent with an <code>Idempotency-Key</code>: the one in the options when given, else one"
            " made up for this call, so that its retries never send twice."
        )
    if op.name == "get" and op.op_id.split(".")[-1] != "get":
        paragraphs.append(
            f"The operation <code>{op.op_id}</code>, which is also the group of the other methods of"
            " this resource."
        )
    paragraphs.append(f"<code>{op.method} {escape(op.path)}</code>")
    return paragraphs


def render_operation(op: Operation, children: set[str]) -> list[str]:
    full = pieces_of(op)
    returns = ", ".join(f"{{@code {r}}}" for r in op.responses)
    lines: list[str] = []
    seen: set[tuple[str, ...]] = set()
    for kept in variants(full):
        key = tuple(erased(p.java_type) for p in kept)
        if key in seen:
            raise SystemExit(f"{op.op_id}: two overloads with the same parameters")
        seen.add(key)
        if not kept and op.name in children:
            continue  # the accessor of the sub-resource of the same name
        lines.append("")
        if len(kept) == len(full):
            tags = param_tags(op, kept, "per-call options, or {@code null}")
            tags.append("@return the answer" + (f" ({returns})" if returns else ""))
            tags.append("@throws BillionSendException when the call fails")
            lines += javadoc(method_doc(op), tags, "  ")
        else:
            summary = escape(op.summary.rstrip(".") + ".") if op.summary else ""
            tags = param_tags(op, kept, "per-call options, or {@code null}")
            tags.append("@return the answer")
            lines += javadoc([summary, f"Same as {link(op.name, full)} without the omitted arguments."], tags, "  ")
        lines.append(f"  public JsonNode {op.name}({signature(kept)}) {{")
        if len(kept) == len(full):
            call = f'Call.of("{op.method}", "{op.path}")'
            chain = [call]
            chain += [f'.path("{wire}", {java})' for wire, java in op.path_params]
            if op.body:
                chain.append(".body(body)")
            if op.query:
                chain.append(".query(query)")
            if op.idempotent:
                chain.append(".idempotent()")
            if op.batch_validation:
                chain.append(".batchValidation()")
            if not op.auth:
                chain.append(".noAuth()")
            lines += render_call("execute", chain, "options")
        else:
            lines.append(f"    return {op.name}({delegate_args(full, kept)});")
        lines.append("  }")
    if op.paginated:
        lines += render_paginator(op)
    return lines


def render_call(target: str, chain: list[str], rest: str) -> list[str]:
    """``return transport.<target>(<chain>, <rest>);`` on one line, or folded."""
    one = f"    return transport.{target}({''.join(chain)}, {rest});"
    if len(one) <= WIDTH:
        return [one]
    out = [f"    return transport.{target}(", "        " + chain[0]]
    out += ["            " + c for c in chain[1:]]
    out[-1] += ","
    out.append(f"        {rest});")
    return out


def render_paginator(op: Operation) -> list[str]:
    full = pieces_of(op, body=False)
    name = op.name + "All"
    lines: list[str] = []
    for kept in variants(full):
        lines.append("")
        tags = param_tags(op, kept, "per-call options for every page, or {@code null}")
        tags.append("@return the items, fetched as the loop asks for them")
        if len(kept) == len(full):
            paragraphs = [
                f"Every item of {link(op.name, pieces_of(op))}, fetching pages as the loop asks for them.",
                "Walks in the list's own order from <code>after</code> (or the first page) on; start with"
                " <code>before</code> instead to walk the other way. A failed page is thrown as its"
                " {@link BillionSendException}.",
            ]
        else:
            paragraphs = [
                f"Every item of {link(op.name, pieces_of(op))}, fetching pages as the loop asks for them.",
                f"Same as {link(name, full)} without the omitted arguments.",
            ]
        lines += javadoc(paragraphs, tags, "  ")
        lines.append(f"  public CursorIterable {name}({signature(kept)}) {{")
        if len(kept) == len(full):
            args = ", ".join([java for _, java in op.path_params] + ["page", "options"])
            lines.append(f"    return new CursorIterable(page -> {op.name}({args}), query);")
        else:
            lines.append(f"    return {name}({delegate_args(full, kept)});")
        lines.append("  }")
    return lines


def render_stream(op: Operation) -> list[str]:
    full = pieces_of(op, options_type="EventStreamOptions")
    lines: list[str] = []
    ends = "EventStream.INBOX_GONE_EVENTS" if op.path_params else "Set.of()"
    for kept in variants(full):
        lines.append("")
        tags = param_tags(op, kept, "stream options (resume position, reconnects, timeout), or {@code null}")
        tags.append("@return the open stream; close it when done")
        if len(kept) == len(full):
            paragraphs = method_doc(op)
            paragraphs.insert(
                -1,
                "Returns once the stream is open, or throws the error that refused it. Iterate the"
                " stream inside try-with-resources; it reconnects with <code>Last-Event-ID</code>"
                " after a dropped connection."
                + (
                    " It ends after this inbox's <code>inbox.deleted</code> or <code>inbox.expired</code>."
                    if op.path_params
                    else ""
                ),
            )
            tags.append("@throws BillionSendException when the stream cannot open")
        else:
            summary = escape(op.summary.rstrip(".") + ".") if op.summary else ""
            paragraphs = [summary, f"Same as {link(op.name, full)} without the omitted arguments."]
        lines += javadoc(paragraphs, tags, "  ")
        lines.append(f"  public EventStream {op.name}({signature(kept)}) {{")
        if len(kept) == len(full):
            chain = [f'Call.of("GET", "{op.path}")']
            chain += [f'.path("{wire}", {java})' for wire, java in op.path_params]
            if op.query:
                chain.append(".query(query)")
            lines += render_call("stream", chain, f"options, {ends}")
        else:
            lines.append(f"    return {op.name}({delegate_args(full, kept)});")
        lines.append("  }")
    return lines


def class_name(group: tuple[str, ...]) -> str:
    return "".join(pascal(g) for g in group) + "Resource"


def render_resource(group: tuple[str, ...], ops: list[Operation], children: list[tuple[str, ...]]) -> str:
    cls = class_name(group)
    child_names = {c[-1] for c in children}
    uses_stream = any(op.stream for op in ops)
    uses_set = any(op.stream and not op.path_params for op in ops)
    imports = ["com.billionsend.BillionSendException"]
    if any(op.paginated for op in ops):
        imports.append("com.billionsend.CursorIterable")
    if uses_stream:
        imports += ["com.billionsend.EventStream", "com.billionsend.EventStreamOptions"]
    imports += ["com.billionsend.RequestOptions", "com.billionsend.internal.Call", "com.billionsend.internal.Transport"]
    imports.append("com.fasterxml.jackson.databind.JsonNode")
    if any(op.query for op in ops):
        imports.append("java.util.Map")
    if uses_set:
        imports.append("java.util.Set")
    title = " ".join(re.sub(r"([a-z])([A-Z])", r"\1 \2", g).lower() for g in group)
    lines = [HEADER, "package com.billionsend.resources;", ""]
    lines += [f"import {i};" for i in sorted(set(imports))]
    lines.append("")
    lines += javadoc(
        [
            f"Operations on {title}: <code>client.{'().'.join(group)}()</code>.",
            "Made by the client; every method throws a {@link BillionSendException} subclass when the call fails.",
        ],
        [],
        "",
    )
    lines.append(f"public final class {cls} {{")
    lines.append("  private final Transport transport;")
    for child in children:
        lines.append(f"  private final {class_name(child)} {child[-1]};")
    lines.append("")
    lines += javadoc(["Made by the client."], ["@param transport the HTTP layer"], "  ")
    lines.append(f"  public {cls}(Transport transport) {{")
    lines.append("    this.transport = transport;")
    for child in children:
        lines.append(f"    this.{child[-1]} = new {class_name(child)}(transport);")
    lines.append("  }")
    for child in children:
        lines.append("")
        lines += javadoc([f"<code>{'.'.join(child)}</code> operations."], ["@return the resource"], "  ")
        lines.append(f"  public {class_name(child)} {child[-1]}() {{")
        lines.append(f"    return {child[-1]};")
        lines.append("  }")
    for op in ops:
        lines += render_stream(op) if op.stream else render_operation(op, child_names)
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_api(roots: list[tuple[str, ...]]) -> str:
    lines = [HEADER, "package com.billionsend;", ""]
    imports = ["com.billionsend.internal.Transport"] + [
        f"com.billionsend.resources.{class_name(r)}" for r in roots
    ]
    lines += [f"import {i};" for i in sorted(imports)]
    lines.append("")
    lines += javadoc(
        [
            "The resource groups of the BillionSend API, one accessor each. {@link BillionSend} is the"
            " client; this class only holds the generated accessors.",
        ],
        [],
        "",
    )
    lines.append("public abstract class BillionSendApi {")
    for root in roots:
        lines.append(f"  private final {class_name(root)} {root[0]};")
    lines.append("")
    lines += javadoc(["Wires every resource to the transport."], ["@param transport the HTTP layer"], "  ")
    lines.append("  BillionSendApi(Transport transport) {")
    for root in roots:
        lines.append(f"    this.{root[0]} = new {class_name(root)}(transport);")
    lines.append("  }")
    for root in roots:
        lines.append("")
        lines += javadoc([f"<code>{root[0]}</code> operations."], ["@return the resource"], "  ")
        lines.append(f"  public {class_name(root)} {root[0]}() {{")
        lines.append(f"    return {root[0]};")
        lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> dict[Path, str]:
    spec = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    ops = build_operations(spec)
    # One operation can also be the group of others (emails.metrics beside
    # emails.metrics.links): it becomes that group's get(), so that
    # client.emails().metrics() stays the group's accessor.
    group_names = {op.group[:i] for op in ops for i in range(1, len(op.group) + 1)}
    for op in ops:
        own = (*op.group, op.name)
        if own in group_names:
            if any(o.group == own and o.name == "get" for o in ops):
                raise SystemExit(f"{op.op_id}: is a group that already has a get operation")
            op.group, op.name = own, "get"
    groups: dict[tuple[str, ...], list[Operation]] = {}
    for op in ops:
        groups.setdefault(op.group, []).append(op)
        for i in range(1, len(op.group)):
            groups.setdefault(op.group[:i], [])
    outputs: dict[Path, str] = {}
    for group in sorted(groups):
        children = sorted(g for g in groups if len(g) == len(group) + 1 and g[: len(group)] == group)
        outputs[RESOURCES / f"{class_name(group)}.java"] = render_resource(group, groups[group], children)
    roots = sorted(g for g in groups if len(g) == 1)
    outputs[API_OUT] = render_api(roots)
    return outputs


def generated_files() -> set[Path]:
    found = set(RESOURCES.glob("*Resource.java")) if RESOURCES.exists() else set()
    if API_OUT.exists():
        found.add(API_OUT)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the SDK's resource classes.")
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args(argv)

    outputs = generate()
    stale_files = sorted(generated_files() - set(outputs))
    if args.check:
        stale = [
            t for t, text in outputs.items() if not t.exists() or t.read_text(encoding="utf-8") != text
        ] + stale_files
        if stale:
            names = ", ".join(str(t.relative_to(ROOT)) for t in stale)
            print(f"generated files are stale, run `python3 scripts/generate.py`: {names}")
            return 1
        print(f"generated files match the snapshot ({len(outputs)} files)")
        return 0
    for target in stale_files:
        target.unlink()
    for target, text in outputs.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    print(f"wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
